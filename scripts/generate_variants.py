#!/usr/bin/env python3
"""Generate src/variants.rs: the GL 1.1 type variants of glVertex, glTexCoord, glNormal, glColor,
glRect and the double matrix calls, exactly as the C renderer defines them (integer colors and
normals are normalized (2c + 1)/(2^b - 1) for signed types, vertices and texcoords are not)."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
existing = set()
for source in (root / 'src').glob('*.rs'):
    if source.name == 'variants.rs':
        continue
    existing |= set(re.findall(r'extern "C" fn (gl\w+)', source.read_text()))

RUST = {'d': 'f64', 'f': 'f32', 'i': 'i32', 's': 'i16', 'b': 'i8', 'ub': 'u8', 'ui': 'u32', 'us': 'u16'}
out = ['// Generated by scripts/generate_variants.py; do not edit.', '#![allow(clippy::all)]', 'use crate::{immediate::*, matrix::*};', '']
emitted = set()

def emit(name, args, body):
    if name in existing or name in emitted:
        return
    emitted.add(name)
    params = ', '.join(f'{n}: {t}' for n, t in args)
    out.append(f'#[no_mangle]\npub unsafe extern "C" fn {name}({params}) {{\n    {body}\n}}\n')

def f32_of(t, expr, signed_norm=None):
    """Value as f32; signed_norm: bits for (2c + 1)/(2^bits - 1) normalization, 'u': unsigned."""
    if t in ('d', 'f'):
        return f'{expr} as f32'
    if signed_norm == 'u32':
        return f'({expr} as f64 / 4294967295.) as f32'
    if signed_norm == 'u16':
        return f'{expr} as f32 / 65535.'
    if signed_norm == 'i32':
        return f'((2. * {expr} as f64 + 1.) / 4294967295.) as f32'
    if signed_norm == 'i16':
        return f'(2. * {expr} as f32 + 1.) / 65535.'
    if signed_norm == 'i8':
        return f'(2. * {expr} as f32 + 1.) / 255.'
    return f'{expr} as f32'

def components(prefix, n):
    return ['x', 'y', 'z', 'w'][:n] if prefix == 'Vertex' else ['s', 't', 'r', 'q'][:n]

def vec_name(base, n, suffix):
    return f'gl{base}{n}{suffix}v'

# glVertex{2,3,4}{d,f,i,s}{,v}
for n in (2, 3, 4):
    for t in 'dfis':
        ty = RUST[t]
        names = ['x', 'y', 'z', 'w'][:n]
        pad = ['0.', '0.', '1.'] if False else None
        full = [f'{c} as f32' for c in names] + ['0.'] * (3 - n if n < 3 else 0) + (['1.'] if n < 4 else [])
        # glVertex2: z = 0, w = 1; glVertex3: w = 1
        vals = [f'{c} as f32' for c in names]
        if n == 2:
            vals += ['0.', '1.']
        elif n == 3:
            vals += ['1.']
        emit(f'glVertex{n}{t}', [(c, ty) for c in names], f'glVertex4f({", ".join(vals)});')
        reads = [f'v.add({i}).read_unaligned() as f32' for i in range(n)]
        if n == 2:
            reads += ['0.', '1.']
        elif n == 3:
            reads += ['1.']
        emit(f'glVertex{n}{t}v', [('v', f'*const {ty}')], f'if v.is_null() {{ return; }}\n    glVertex4f({", ".join(reads)});')

# glTexCoord{1,2,3,4}
for n in (1, 2, 3, 4):
    for t in 'dfis':
        ty = RUST[t]
        names = ['s', 't', 'r', 'q'][:n]
        pad = ['0.'] * (3 - n if n < 4 else 0)
        def vals(src):
            v = list(src)
            if n < 4:
                v += ['0.'] * (3 - n) + ['1.']
            return ', '.join(v)
        emit(f'glTexCoord{n}{t}', [(c, ty) for c in names], f'glTexCoord4f({vals([f"{c} as f32" for c in names])});')
        emit(f'glTexCoord{n}{t}v', [('v', f'*const {ty}')], f'if v.is_null() {{ return; }}\n    glTexCoord4f({vals([f"v.add({i}).read_unaligned() as f32" for i in range(n)])});')

# glNormal3{b,d,f,i,s}
norm = {'b': 'i8', 'i': 'i32', 's': 'i16'}
for t in 'bdfis':
    ty = RUST[t]
    names = ['nx', 'ny', 'nz']
    f = lambda e: f32_of(t, e, norm.get(t))
    emit(f'glNormal3{t}', [(c, ty) for c in names], f'glNormal3f({", ".join(f(c) for c in names)});')
    emit(f'glNormal3{t}v', [('v', f'*const {ty}')], f'if v.is_null() {{ return; }}\n    glNormal3f({", ".join(f(f"v.add({i}).read_unaligned()") for i in range(3))});')

# glColor{3,4}{b,d,f,i,s,ub,ui,us}
cnorm = {'b': 'i8', 'i': 'i32', 's': 'i16', 'ui': 'u32', 'us': 'u16'}
for n in (3, 4):
    for t in ['b', 'd', 'f', 'i', 's', 'ub', 'ui', 'us']:
        ty = RUST[t]
        names = ['red', 'green', 'blue', 'alpha'][:n]
        if t == 'ub':
            a = ', 255' if n == 3 else ''
            emit(f'glColor{n}ub', [(c, ty) for c in names], f'glColor4ub({", ".join(names)}{a});')
            reads = ', '.join(f'v.add({i}).read_unaligned()' for i in range(n)) + (', 255' if n == 3 else '')
            emit(f'glColor{n}ubv', [('v', f'*const {ty}')], f'if v.is_null() {{ return; }}\n    glColor4ub({reads});')
            continue
        f = lambda e: f32_of(t, e, cnorm.get(t))
        tail = ', 1.' if n == 3 else ''
        emit(f'glColor{n}{t}', [(c, ty) for c in names], f'glColor4f({", ".join(f(c) for c in names)}{tail});')
        emit(f'glColor{n}{t}v', [('v', f'*const {ty}')], f'if v.is_null() {{ return; }}\n    glColor4f({", ".join(f(f"v.add({i}).read_unaligned()") for i in range(n))}{tail});')

# glRect
for t in 'dfis':
    ty = RUST[t]
    emit(f'glRect{t}', [(c, ty) for c in ('x1', 'y1', 'x2', 'y2')], 'glRectf(x1 as f32, y1 as f32, x2 as f32, y2 as f32);')
    emit(f'glRect{t}v', [('v1', f'*const {ty}'), ('v2', f'*const {ty}')],
         'if v1.is_null() || v2.is_null() { return; }\n    glRectf(v1.read_unaligned() as f32, v1.add(1).read_unaligned() as f32, v2.read_unaligned() as f32, v2.add(1).read_unaligned() as f32);')

# Double matrix calls
emit('glLoadMatrixd', [('m', '*const f64')], 'if m.is_null() { return; }\n    let f: [f32; 16] = core::array::from_fn(|i| m.add(i).read_unaligned() as f32);\n    glLoadMatrixf(f.as_ptr());')
emit('glMultMatrixd', [('m', '*const f64')], 'if m.is_null() { return; }\n    let f: [f32; 16] = core::array::from_fn(|i| m.add(i).read_unaligned() as f32);\n    glMultMatrixf(f.as_ptr());')
emit('glTranslated', [('x', 'f64'), ('y', 'f64'), ('z', 'f64')], 'glTranslatef(x as f32, y as f32, z as f32);')
emit('glRotated', [('angle', 'f64'), ('x', 'f64'), ('y', 'f64'), ('z', 'f64')], 'glRotatef(angle as f32, x as f32, y as f32, z as f32);')
emit('glScaled', [('x', 'f64'), ('y', 'f64'), ('z', 'f64')], 'glScalef(x as f32, y as f32, z as f32);')

(root / 'src/variants.rs').write_text('\n'.join(out))
print(len(emitted), 'functions')
